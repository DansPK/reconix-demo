"""Render `report.report_data()` as a Word (.docx) document: the editable report.

It follows the PDF (report_html.py) section for section, in the same order and under the same
headings, from the same outline (report_view.py): the cover, 1 Executive summary (with the
severity counts), 2 Findings summary, the changes since the last assessment, 3 Approved scope &
limitations (with its disclaimer), then on a new page 4 Detailed findings (severity order, with
the analyst's note) and 5 Policy & governance. Each finding also lists its references.

Every value is already redacted and cleaned by `report_data()` (redact.py drops the control
characters XML can't hold), and python-docx escapes the XML. Should a value still be refused,
`write_docx` raises StoreValidationError, so the screen shows why instead of failing. Writes a
binary file straight to `path`; enabled when python-docx is installed (`HAS_DOCX`).
"""

import importlib.util
from typing import Any, Dict, List, Optional, Sequence, Tuple

from . import report_view as view
from .errors import StoreValidationError

HAS_DOCX = importlib.util.find_spec("docx") is not None

KV_STYLE = "Light List Accent 1"
GRID_STYLE = "Light Grid Accent 1"
# Column shares (of the text width) for the tables whose first column is short.
KV_WIDTHS = (0.3, 0.7)
FINDINGS_WIDTHS = (0.08, 0.42, 0.12, 0.08, 0.12, 0.18)


# --- building blocks ---------------------------------------------------------------------------
def _widths(table, shares: Sequence[float], text_width) -> None:
    """Fix each column's width to its share of the text width (Word honours the cells')."""
    table.autofit = False
    for column, share in zip(table.columns, shares):
        for cell in column.cells:
            cell.width = int(text_width * share)


def _kv(doc, rows: List[Tuple[str, str]], text_width) -> None:
    table = doc.add_table(rows=0, cols=2)
    table.style = KV_STYLE
    for label, value in rows:
        cells = table.add_row().cells
        cells[0].text, cells[1].text = label, str(value)
    _widths(table, KV_WIDTHS, text_width)


def _grid(doc, head: Sequence[str], rows: List[List[str]], empty: str, text_width,
          shares: Optional[Sequence[float]] = None) -> None:
    """A table with a header row, or the `empty` line when there are no rows."""
    if not rows:
        doc.add_paragraph(empty)
        return
    table = doc.add_table(rows=1, cols=len(head))
    table.style = GRID_STYLE
    for i, label in enumerate(head):
        table.rows[0].cells[i].text = label
    for row in rows:
        cells = table.add_row().cells
        for i, value in enumerate(row):
            cells[i].text = str(value)
    if shares:
        _widths(table, shares, text_width)


def _heading(doc, number: str, tag: str = "") -> None:
    doc.add_heading(f"{number} {view.section(number)}", level=1)
    if tag:
        _note(doc, tag)


def _labelled(doc, label: str, value: str) -> None:
    """A bold label, then the value, as one paragraph."""
    para = doc.add_paragraph()
    para.add_run(f"{label}: ").bold = True
    para.add_run(value)


def _note(doc, text: str) -> None:
    para = doc.add_paragraph()
    para.add_run(text).italic = True


# --- the sections ----------------------------------------------------------------------------
def _cover(doc, data: Dict[str, Any], text_width) -> None:
    doc.add_heading(view.TITLE, level=0)
    doc.add_paragraph(view.subtitle(data))
    _labelled(doc, "Target", data.get("target") or "—")
    _kv(doc, view.cover_rows(data), text_width)
    doc.add_paragraph().add_run(view.CONFIDENTIAL).bold = True
    para = doc.add_paragraph()
    para.add_run("Generated by Reconix. ").bold = True
    para.add_run(view.GENERATED_NOTE)


def _summary(doc, data: Dict[str, Any], text_width) -> None:
    findings = data["findings"]
    _heading(doc, "1")
    para = doc.add_paragraph()
    for text, bold in view.summary(data):
        para.add_run(text).bold = bold
    columns = view.count_columns(findings)
    _grid(doc, [label for label, _n in columns], [[str(n) for _label, n in columns]], "",
          text_width)
    spread = view.distribution(findings)
    if spread:
        doc.add_paragraph("Severity distribution: " + " · ".join(
            f"{n} {sev.title()} ({pct}%)" for sev, n, pct in spread))


def _findings_summary(doc, data: Dict[str, Any], text_width) -> None:
    findings = view.ordered(data["findings"])
    _heading(doc, "2", f"{len(findings)} findings")
    _grid(doc, view.FINDINGS_HEAD, [view.finding_row(f) for f in findings],
          view.NO_FINDINGS_ROW, text_width, FINDINGS_WIDTHS)


def _retest(doc, data: Dict[str, Any], text_width) -> None:
    retest = data.get("retest")
    if not retest:
        return
    counts = retest["counts"]
    doc.add_heading(view.RETEST_HEADING, level=1)
    _note(doc, f"vs {retest['previous_label']}")
    _grid(doc, ["New", "Resolved", "Recurring"],
          [[str(counts["new"]), str(counts["resolved"]), str(counts["recurring"])]], "",
          text_width)
    if retest["new"]:
        doc.add_paragraph("New this run: " + ", ".join(i["title"] for i in retest["new"]) + ".")


def _scope(doc, data: Dict[str, Any], text_width) -> None:
    _heading(doc, "3")
    _kv(doc, view.scope_rows(data), text_width)
    doc.add_paragraph(view.DISCLAIMER)


def _finding(doc, finding: Dict[str, Any], text_width) -> None:
    doc.add_heading(f"{finding['id']} · {finding['title']}", level=2)
    score = view.cvss(finding)
    doc.add_paragraph(" · ".join(
        [finding["severity"].title(), finding["validation"].title(), view.status_label(finding)]
        + ([f"CVSS {score}"] if score != "—" else [])))
    _kv(doc, view.finding_meta(finding), text_width)
    doc.add_heading("Description", level=3)
    doc.add_paragraph(finding.get("description") or "—")
    doc.add_heading("Evidence & validation (masked)", level=3)
    evidence = doc.add_paragraph("\n".join(str(line) for line in finding.get("evidence", []))
                                 or "—")
    evidence.style = "Intense Quote"
    doc.add_heading("Impact", level=3)
    doc.add_paragraph(finding.get("impact") or "—")
    doc.add_heading("Remediation", level=3)
    doc.add_paragraph(finding.get("remediation") or "—")
    if finding.get("triage_note"):
        doc.add_heading("Analyst note", level=3)
        doc.add_paragraph(finding["triage_note"])
    if finding.get("references"):
        _labelled(doc, "References", ", ".join(finding["references"]))


def _governance(doc, data: Dict[str, Any], text_width) -> None:
    _heading(doc, "5", "Audit trail")
    blocked = view.blocked_rows(data)
    doc.add_heading(f"Blocked by policy · {len(blocked)}", level=3)
    _grid(doc, view.BLOCKED_HEAD, blocked, view.NO_BLOCKED, text_width, KV_WIDTHS)
    approvals = view.approval_rows(data)
    doc.add_heading(f"Human approvals · {len(approvals)}", level=3)
    _grid(doc, view.APPROVALS_HEAD, approvals, view.NO_APPROVALS, text_width)


# --- the document ------------------------------------------------------------------------------
def _build(data: Dict[str, Any], path) -> None:
    from docx import Document
    from docx.enum.text import WD_BREAK
    from docx.shared import Cm

    doc = Document()
    page = doc.sections[0]
    page.page_width, page.page_height = Cm(21), Cm(29.7)            # A4, like the PDF
    for side in ("left_margin", "right_margin", "top_margin", "bottom_margin"):
        setattr(page, side, Cm(2))
    text_width = page.page_width - page.left_margin - page.right_margin
    first_foot, last_foot = view.footers(data)

    _cover(doc, data, text_width)
    _summary(doc, data, text_width)
    _findings_summary(doc, data, text_width)
    _retest(doc, data, text_width)
    _scope(doc, data, text_width)
    _note(doc, f"{view.FOOTER_TOOL} · {first_foot}")

    doc.add_paragraph().add_run().add_break(WD_BREAK.PAGE)        # the PDF's second sheet
    _heading(doc, "4")
    findings = view.ordered(data["findings"])
    for finding in findings:
        _finding(doc, finding, text_width)
    if not findings:
        _note(doc, "No findings.")
    _governance(doc, data, text_width)
    _note(doc, f"Reconix — Confidential · {last_foot}")
    doc.save(str(path))


def write_docx(data: Dict[str, Any], path) -> None:
    """Write the full report as a .docx file at `path`.

    python-docx refuses text XML can't hold with a ValueError; `report_data()` has already
    cleaned it out, and anything left is the store's verdict, not a crash.
    """
    try:
        _build(data, path)
    except ValueError as exc:
        raise StoreValidationError(
            "The Word report couldn't be written: a value holds characters a .docx can't "
            "store.") from exc
