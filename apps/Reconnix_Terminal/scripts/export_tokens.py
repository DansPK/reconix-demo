"""Write the web dashboard's color tokens from reconix/theme.py (the single source).

    python scripts/export_tokens.py        # → web/src/styles/tokens.css

With a light set, light values go on :root and dark values on [data-theme="dark"] (set by a
theme toggle) and under prefers-color-scheme. With a dark set only (the current dashboard is
dark only), the dark values go on :root.
"""

import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))

from reconix.theme import WEB_TOKENS  # noqa: E402

OUT = ROOT / "web" / "src" / "styles" / "tokens.css"


def block(values: dict, indent: str = "  ") -> str:
    return "\n".join(f"{indent}--{name}: {value};" for name, value in values.items())


HEADER = "/* GENERATED by scripts/export_tokens.py from reconix/theme.py. Do not edit. */\n"


def css_for(tokens: dict) -> str:
    if "light" not in tokens:
        return HEADER + f":root {{\n{block(tokens['dark'])}\n  color-scheme: dark;\n}}\n"
    return (
        HEADER
        + f":root {{\n{block(tokens['light'])}\n  color-scheme: light;\n}}\n"
        + "@media (prefers-color-scheme: dark) {\n"
        + f"  :root:not([data-theme=\"light\"]) {{\n{block(tokens['dark'], '    ')}\n"
        + "    color-scheme: dark;\n  }\n}\n"
        + f":root[data-theme=\"dark\"] {{\n{block(tokens['dark'])}\n  color-scheme: dark;\n}}\n"
    )


def main() -> None:
    css = css_for(WEB_TOKENS)
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text(css, encoding="utf-8")
    print(f"wrote {OUT.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
