/* The combined report (CombinedReport, ../combined/select.ts) as an editable Word document: the
   same ten sections as its PDF (../combined/html.ts), from the same model, so the two never
   disagree. The route masks every run before combining them. */
import "server-only";

import type { Severity } from "@/lib/data/schema";

import { shortDate, title } from "../html";
import type { CombinedReport, Occurrence, RunSection, UniqueFinding } from "../combined/select";
import { type Block, docxFile } from "./ooxml";

const score = (cvss: number | null) => (cvss === null ? "—" : cvss.toFixed(1));
const plural = (n: number, one: string, many = `${one}s`) => `${n} ${n === 1 ? one : many}`;
const confirmed = (yes: boolean) => (yes ? "Confirmed" : "Unconfirmed");

const SECTIONS = [
  "Cover",
  "Table of contents",
  "Executive summary",
  "Assessment overview",
  "Combined findings summary",
  "Individual assessment sections",
  "Evidence & technical details",
  "Risk & remediation priorities",
  "Limitations",
  "Appendix & references",
];
const h1 = (n: number): Block => ({ kind: "heading", level: 1, text: `${n} ${SECTIONS[n - 1]}` });

function cover(r: CombinedReport, generated: string): Block[] {
  const { cover: c, summary: s } = r;
  const span = c.from && c.to ? (shortDate(c.from) === shortDate(c.to) ? shortDate(c.from) : `${shortDate(c.from)} → ${shortDate(c.to)}`) : "—";
  const rows: [string, string][] = [
    ["Targets", c.targets.join(", ") || "—"],
    ["Assessments combined", String(s.runs)],
    ...(c.clients.length ? ([["Client", c.clients.join(", ")]] as [string, string][]) : []),
    ["Assessment window", span],
    ["Operators", c.operators.join(", ") || "—"],
    ["Templates", c.templates.join(", ") || "—"],
    ["Report date", shortDate(generated)],
    ["Unique findings", `${s.unique} (${plural(s.occurrences, "occurrence")})`],
  ];
  return [
    { kind: "title", text: r.title },
    { kind: "subtitle", text: `AI-Assisted Authorized Penetration Tests — ${plural(s.runs, "run")} in one report` },
    { kind: "kv", rows },
    { kind: "para", runs: [{ text: "CONFIDENTIAL — AUTHORIZED RECIPIENTS ONLY", bold: true }] },
    {
      kind: "para",
      note: true,
      runs: [
        `Generated by Reconix. This report combines the saved copies of ${plural(s.runs, "assessment")}; every number counts what those copies hold. ` +
          "Credentials and one-time codes are never stored or shown, and evidence is masked at the source.",
      ],
    },
    { kind: "heading", level: 3, text: "Runs in this report" },
    { kind: "table", head: ["Run", "Template", "Target", "Status", "Saved copy"], rows: c.runs.map((x) => [x.id, x.template, x.target, x.status, x.uid]) },
  ];
}

function summary(r: CombinedReport): Block[] {
  const s = r.summary;
  const breakdown =
    (Object.keys(s.uniqueBySeverity) as Severity[])
      .filter((k) => s.uniqueBySeverity[k])
      .map((k) => `${s.uniqueBySeverity[k]} ${title(k)}`)
      .join(", ") || "no findings";
  const top = s.topRisks[0];
  const approval =
    s.scopesApproved === s.runs
      ? " Every run tested inside a scope the operator approved; intrusive actions ran only after explicit, single-use approval."
      : ` ${s.runs - s.scopesApproved} of the runs had no approved scope: see Limitations.`;
  return [
    h1(3),
    {
      kind: "para",
      runs: [
        `Reconix combined ${plural(s.runs, "assessment")} of ${plural(r.cover.targets.length, "target")} (${r.cover.templates.join(", ") || "—"}). ` +
          `Together they recorded ${plural(s.occurrences, "finding occurrence")}, which are ${plural(s.unique, "unique finding")} — ${breakdown}. ` +
          `The highest severity is ${title(s.worst ?? "none")}${top ? `, led by ${top.title} (seen in ${plural(top.runs.length, "run")})` : ""}. ` +
          `${s.confirmed} of the unique findings ${s.confirmed === 1 ? "is" : "are"} confirmed with evidence in at least one run.${approval}`,
      ],
    },
    {
      kind: "table",
      head: ["Unique", "Occurrences", "Confirmed", ...s.byStatus.map((x) => x.status)],
      rows: [[String(s.unique), String(s.occurrences), String(s.confirmed), ...s.byStatus.map((x) => String(x.count))]],
    },
    { kind: "heading", level: 3, text: "Top risks" },
    {
      kind: "table",
      head: ["#", "Top risk", "Severity", "CVSS", "Runs"],
      rows: s.topRisks.map((u, i) => [String(i + 1), u.title, title(u.severity), score(u.cvss), u.runs.join(", ")]),
      weights: [0.6, 5, 1.6, 1.1, 3],
      empty: "No findings to rank.",
    },
  ];
}

function overview(r: CombinedReport): Block[] {
  return [
    h1(4),
    {
      kind: "table",
      head: ["Run", "Template", "Target", "Status", "Window", "Findings", "Plan", "Requests", "Approvals"],
      rows: r.runs.map((x) => [
        x.id,
        x.template,
        x.target,
        x.status,
        x.startedAt ? `${shortDate(x.startedAt)}${x.finishedAt ? ` → ${shortDate(x.finishedAt)}` : " → …"}` : "—",
        String(x.findings.length),
        x.plan.total ? `${x.plan.done}/${x.plan.total}` : "—",
        String(x.requests),
        `${x.approvals.approved}/${x.approvals.total}`,
      ]),
    },
    { kind: "para", note: true, runs: ["Findings count the occurrences this report includes; Approvals are the gated actions approved of those requested."] },
  ];
}

function findings(r: CombinedReport): Block[] {
  return [
    h1(5),
    { kind: "para", note: true, runs: ["A unique finding is the same title, weakness (CWE) and target; each run it was seen in is an occurrence."] },
    {
      kind: "table",
      head: ["Finding", "Severity", "CVSS", "CWE", "Target", "Validation", "Seen in"],
      rows: r.findings.map((u) => [u.title, title(u.severity), score(u.cvss), u.cwe ?? "—", u.target || "—", confirmed(u.confirmed), u.runs.join(", ")]),
      weights: [4.2, 1.6, 1.1, 1.5, 2.4, 1.9, 2.2], // the title takes the widest share
      empty: "No findings were recorded in these runs.",
    },
  ];
}

function runSection(x: RunSection, i: number): Block[] {
  const out: Block[] = [{ kind: "heading", level: 2, text: `6.${i + 1} ${x.id} — ${x.template}` }, { kind: "kv", rows: x.details.map((d) => [d.label, d.value]) }];
  if (x.missing.length) out.push({ kind: "para", note: true, runs: [`Not saved for this run: ${x.missing.join(", ")}.`] });
  out.push({ kind: "heading", level: 3, text: "Scope" });
  const s = x.scope;
  out.push(
    s
      ? {
          kind: "kv",
          rows: [
            ["Approval status", s.approved ? "Approved" : title(s.status || "not approved")],
            ["Allowed actions", s.actions.join(", ") || "—"],
            ["Allowed methods", s.methods.join(", ") || "—"],
            ["Excluded paths", s.excluded.join(", ") || "none"],
            ["Ports", s.ports.join(", ") || "default"],
            ["Time limit", `${s.timeLimitMinutes} minutes`],
            ["Tools", s.tools.join(", ") || "—"],
          ],
        }
      : { kind: "para", note: true, runs: ["No Scope Manifest was saved for this run."] },
  );
  out.push(
    { kind: "heading", level: 3, text: x.plan.total ? `Plan · ${x.plan.done} of ${x.plan.total} steps done` : "Plan" },
    x.plan.total ? { kind: "bullets", items: x.plan.steps.map((p) => [`${p.label} · ${p.status}`]) } : { kind: "para", note: true, runs: ["No plan was saved for this run."] },
    { kind: "heading", level: 3, text: "Policy & approvals" },
    {
      kind: "para",
      runs: [
        `${x.blocked} out-of-scope request(s) were blocked by policy; ${x.approvals.approved} gated action(s) approved, ${x.approvals.rejected} rejected` +
          `${x.approvals.pending ? `, ${x.approvals.pending} still waiting` : ""} (${x.approvals.total} requested).`,
      ],
    },
    { kind: "heading", level: 3, text: `Findings · ${x.findings.length}` },
    {
      kind: "table",
      head: ["ID", "Finding", "Severity", "CVSS", "Validation", "Status", "Tool"],
      rows: x.findings.map((o) => [o.id, o.title, title(o.severity), score(o.cvss), title(o.validation), o.status || "open", o.tool || "—"]),
      weights: [1.4, 4.4, 1.6, 1.1, 1.9, 1.5, 1.6],
      empty: x.finished ? "This run completed and recorded no findings." : "No findings in this report for this run.",
    },
  );
  return out;
}

function occurrence(o: Occurrence, withEvidence: boolean): Block[] {
  const rows: [string, string][] = [
    ["Run", o.runId],
    ["Finding", `${o.id} · ${title(o.severity)} · ${title(o.validation)} · ${o.status || "open"} · CVSS ${score(o.cvss)}`],
    ["Saved copy", o.uid],
    ["Location", o.location || "—"],
    ["Detected by", o.tool || "—"],
    ["Mapping", o.references.join(", ") || "—"],
  ];
  if (o.cvssVector) rows.push(["CVSS vector", o.cvssVector]);
  const out: Block[] = [{ kind: "kv", rows }, { kind: "para", runs: [{ text: "Description: ", bold: true }, o.description || "—"] }];
  if (withEvidence) out.push({ kind: "para", runs: [{ text: "Evidence & validation (masked)", bold: true }] }, { kind: "pre", lines: o.evidence });
  out.push({ kind: "para", runs: [{ text: "Impact: ", bold: true }, o.impact || "—"] });
  if (o.note) out.push({ kind: "para", runs: [{ text: "Analyst note: ", bold: true }, o.note] });
  return out;
}

function unique(u: UniqueFinding, withEvidence: boolean): Block[] {
  return [
    { kind: "heading", level: 2, text: u.title },
    {
      kind: "kv",
      rows: [
        ["Severity", `${title(u.severity)} · CVSS ${score(u.cvss)} · ${confirmed(u.confirmed)}`],
        ["Target", u.target || "—"],
        ["Weakness", u.cwe ?? "—"],
        ["Category", u.category || "—"],
        ["Seen in", u.runs.join(", ")],
      ],
    },
    { kind: "heading", level: 3, text: plural(u.occurrences.length, "occurrence") },
    ...u.occurrences.flatMap((o) => occurrence(o, withEvidence)),
    { kind: "heading", level: 3, text: "Remediation" },
    { kind: "para", runs: [u.remediation || "—"] },
  ];
}

function appendix(r: CombinedReport): Block[] {
  const a = r.appendix;
  if (!a) return [h1(10), { kind: "para", note: true, runs: ["The appendix was left out by the report's options."] }];
  return [
    h1(10),
    { kind: "heading", level: 3, text: "Tools" },
    { kind: "table", head: ["Tool", "Runs"], rows: a.tools.map((t) => [t.name, t.runs.join(", ")]), empty: "No tools recorded." },
    { kind: "heading", level: 3, text: "Weaknesses (unique findings)" },
    { kind: "table", head: ["CWE", "Findings"], rows: a.weaknesses.map((x) => [x.cwe, String(x.count)]), empty: "No CWE mapped." },
    { kind: "heading", level: 3, text: "References (occurrences)" },
    { kind: "table", head: ["Reference", "Occurrences"], rows: a.references.map((x) => [x.ref, String(x.count)]), empty: "No references." },
    { kind: "heading", level: 3, text: "Saved copies" },
    { kind: "bullets", items: a.uids.map((u) => [{ text: u, mono: true }]) },
  ];
}

/** The combined report's blocks, in its PDF's order. */
function combinedBlocks(r: CombinedReport, now: Date = new Date()): Block[] {
  const generated = now.toISOString();
  const page: Block = { kind: "pagebreak" };
  return [
    ...cover(r, generated),
    page,
    h1(2),
    { kind: "bullets", items: SECTIONS.map((name, i) => [`${i + 1} ${name}`]) },
    page,
    ...summary(r),
    page,
    ...overview(r),
    page,
    ...findings(r),
    page,
    h1(6),
    ...r.runs.flatMap(runSection),
    page,
    h1(7),
    ...(r.options.evidence ? [] : [{ kind: "para", note: true, runs: ["Evidence lines were left out by the report's options."] } as Block]),
    ...(r.findings.length ? r.findings.flatMap((u) => unique(u, r.options.evidence)) : [{ kind: "para", note: true, runs: ["No findings."] } as Block]),
    page,
    h1(8),
    { kind: "para", note: true, runs: ["Ordered by the worst severity seen, then the highest CVSS, then in how many runs the finding appeared."] },
    ...(r.priorities.length
      ? r.priorities.flatMap((p): Block[] => [
          { kind: "heading", level: 3, text: `${p.rank}. ${p.title}` },
          { kind: "para", runs: [`${title(p.severity)} · CVSS ${score(p.cvss)} · ${confirmed(p.confirmed)} · ${p.target || "—"} · seen in ${plural(p.runs.length, "run")}: ${p.runs.join(", ")}`] },
          { kind: "para", runs: [{ text: "Remediation: ", bold: true }, p.remediation || "—"] },
        ])
      : [{ kind: "para", note: true, runs: ["Nothing to prioritise."] } as Block]),
    page,
    h1(9),
    {
      kind: "para",
      note: true,
      runs: [
        "Testing was limited to each run's approved actions, methods and time window. Requests to an excluded path or outside the allowed methods were refused by the policy engine rather than sent. " +
          "Findings reflect only what was observed under these constraints, in the saved copies listed on the cover.",
      ],
    },
    r.limitations.length ? { kind: "bullets", items: r.limitations.map((l) => [l.text]) } : { kind: "para", note: true, runs: ["Every run completed inside an approved scope; nothing was left out."] },
    page,
    ...appendix(r),
    { kind: "para", note: true, runs: [`Reconix — Confidential · ${plural(r.summary.runs, "run")} · Generated ${shortDate(generated)} · End of report`] },
  ];
}

/** The Word file of a combined report. */
export function renderCombinedDocx(r: CombinedReport, now: Date = new Date()): Uint8Array<ArrayBuffer> {
  return docxFile(combinedBlocks(r, now), { title: r.title, created: now.toISOString() });
}
