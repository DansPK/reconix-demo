def rows(system: str, where: str, start: int = 1) -> List[Finding]:
    """The findings of `system` at `where` (a URL, a repository or a host), from id `start`."""
    category, listed = _ROWS[system]
    out = []
    for number, row in enumerate(listed, start):
        validation, key, title, path, tool, refs, description, impact, fix, *evidence = row
        vector, score = _V[key]
        # None is CRITICAL: that is the www.lumina.com SQL injection alone.
        severity = "HIGH" if score >= 7 else "MEDIUM" if score >= 4 else "LOW"
        path = path.format(host=where) if category == "Network" else path
        affected = (path if category == "Network"
                    else f"{where} · {path}" if category == "Source Code" else f"{where}{path}")
        references = sorted(refs.replace("OWASP ", "OWASP_").split(), reverse=True)
        references = [ref.replace("_", " ") for ref in references]     # OWASP first, then CWE
        kind = ("Secret" if tool == "gitleaks" else "Dependency" if tool == "grype" else category)
        out.append(Finding(
            f"{number:03d}", severity, title, path.split(":")[0] if category == "Source Code"
            else path, _VALIDATION[validation], description=description, affected_url=affected,
            impact=impact, remediation=fix, tool=tool, references=references,
            cvss_vector="CVSS:3.1/" + vector, cvss_score=score, category=kind,
            evidence=list(evidence)))
    return out
